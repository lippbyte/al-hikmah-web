export const QURAN_SURAHS = RAW_SURAHS.map(
  ([number, name, ayahs, startJuz, endJuz]) => ({
    number,
    name,
    ayahs,
    startJuz,
    endJuz,
  })
);

export const QURAN_JUZ_LIST = Array.from({ length: 30 }, (_, i) => i + 1);

export function getSurahsByJuz(juzNumber) {
  if (!juzNumber) return QURAN_SURAHS;
  const juz = Number(juzNumber);
  return QURAN_SURAHS.filter((s) => juz >= s.startJuz && juz <= s.endJuz);
}

export function getSurahByNumber(surahNumber) {
  return (
    QURAN_SURAHS.find((s) => s.number === Number(surahNumber)) || QURAN_SURAHS[0]
  );
}
